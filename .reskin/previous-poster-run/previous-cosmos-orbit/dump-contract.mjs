import fs from 'node:fs/promises'

const c = JSON.parse(await fs.readFile('.reskin/content-contract.json', 'utf8'))
console.log('ROUTES', JSON.stringify(c.routes))
console.log('META', JSON.stringify(c.meta))
console.log('\n=== VISIBLE TEXT', c.visibleText.length)
for (const v of c.visibleText) console.log(`${v.count}x | ${v.value}`)
console.log('\n=== HIDDEN TEXT', c.hiddenText.length)
for (const v of c.hiddenText) console.log(`${v.count}x | ${v.value}`)
console.log('\n=== ATTRIBUTES', c.attributes.length)
for (const v of c.attributes) console.log(`${v.count}x | ${v.name}=${v.value}`)
console.log('\n=== FORMS', c.forms.length)
for (const v of c.forms) console.log(`${v.count}x | ${v.tag}:${v.name}:${v.type}`)
console.log('\n=== EVENTS', c.events.length)
for (const v of c.events) console.log(`${v.count}x | ${v.event}:${v.handler}`)
console.log('\n=== LINKS', c.links.length)
for (const v of c.links) console.log(`${v.count}x | ${v.kind}:${v.target}`)
console.log('\n=== ASSETS', c.assets.length)
for (const v of c.assets) console.log(`${v.count}x | ${v.kind}:${v.value}`)
console.log('\n=== BINDINGS', c.bindings.length)
for (const v of c.bindings) console.log(`${v.count}x | ${v.kind}: ${v.expr}`)
